// Pure Docker argv builder for the witness sandbox (PLAN K18, M2 acceptance 2). Design-informed by S39 `d5f9e40`
// cli/sandbox/sandboxrun.ts (buildSandboxCommand, safeMount, removeContainer); implemented here, not vendored
// (PLAN K13). There is deliberately no `--sandbox none` / host-runner branch: the only command this module can
// describe is a `docker run` of a digest-pinned image with the flags below. Nothing here spawns anything.
import { hashCanonical } from "../defectcorpus/hashes.ts";

export const SANDBOX_UID = 10001;
export const SANDBOX_GID = 10001;
/** Wall-clock budget for one sandbox run (host-enforced, then `docker rm --force`). */
export const WITNESS_TIMEOUT_MS = 30_000;
/** Combined stdout + stderr cap (1 MiB); exceeding it stops the container and is never a valid result. */
export const OUTPUT_CAP_BYTES = 1_048_576;
/** Bounded cleanup wait for `docker rm --force` and the presence check. */
export const CLEANUP_TIMEOUT_MS = 10_000;

/** agent-ports labels (agent-ports SKILL rule 3: `agentports.project`, `agentports.instance`, `agentports.owner`). */
export const AGENT_PORTS_PROJECT = "s41-pr-review-judgment";
export const AGENT_PORTS_INSTANCE = "witness-sandbox";

/** Container names are generated by the host (injected randomness) and must match this. */
export const CONTAINER_NAME_PATTERN = /^s41-prj-witness-[a-z0-9]{8,64}$/;
/** `name@sha256:<64 hex>` only; tags (`:latest`) and bare names are refused. Docker repository names are lowercase. */
export const PINNED_IMAGE_PATTERN = /^[a-z0-9][a-z0-9._/-]*@sha256:[0-9a-f]{64}$/;

/** In-container paths. `/in` is a read-only bind of the host staging directory; `/work` is tmpfs. */
export const CONTAINER_INPUT_DIR = "/in";
export const CONTAINER_WORK_DIR = "/work";
export const WITNESS_ENTRY = ["/opt/witness/entry.mjs", "/in/request.json", "/work"] as const;

/**
 * The isolation policy, as data. Every flag here appears in every `docker run` argv; `SANDBOX_POLICY_SHA256` is
 * recorded in the probe receipt so a receipt for an older flag set no longer qualifies the sandbox.
 * PLAN M2.2 flags plus three deliberate additions (see the M2 report): `--memory-swap 1g` (without it Docker allows
 * swap up to twice `--memory`, so the memory bomb would swap instead of being OOM-killed), a `/tmp` tmpfs (the root
 * file system is read-only) and the explicit group in `--user 10001:10001` (a bare uid leaves the process in gid 0).
 */
export const SANDBOX_POLICY = {
  pull: "never",
  remove: true,
  network: "none",
  user: `${SANDBOX_UID}:${SANDBOX_GID}`,
  read_only_root: true,
  cap_drop: "ALL",
  security_opt: "no-new-privileges",
  tmpfs_work: "/work:rw,nosuid,nodev,size=128m,mode=1777",
  tmpfs_tmp: "/tmp:rw,noexec,nosuid,nodev,size=64m,mode=1777",
  memory: "1g",
  memory_swap: "1g",
  cpus: "1",
  pids_limit: "128",
  input_mount: "type=bind,destination=/in,readonly",
  workdir: CONTAINER_WORK_DIR,
  entrypoint: "node",
  timeout_ms: WITNESS_TIMEOUT_MS,
  output_cap_bytes: OUTPUT_CAP_BYTES,
} as const;

export const SANDBOX_POLICY_SHA256: string = hashCanonical({ domain: "pr-review-judgment/sandbox-policy/v1", ...SANDBOX_POLICY });

/** Flags that must never appear: published ports, env injection, extra mounts, privilege. */
export const FORBIDDEN_ARGS = [
  "-p",
  "--publish",
  "--publish-all",
  "-P",
  "-e",
  "--env",
  "--env-file",
  "-v",
  "--volume",
  "--privileged",
  "--cap-add",
  "--device",
  "--pid",
  "--ipc",
  "--userns",
  "--net",
] as const;

export class SandboxArgvError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "SandboxArgvError";
  }
}

export interface SandboxLimits {
  /** 1..30000 ms. Tightening is allowed; loosening is refused. */
  readonly timeoutMs: number;
  /** 1..1048576 bytes. */
  readonly outputCapBytes: number;
}

export const DEFAULT_LIMITS: SandboxLimits = Object.freeze({ timeoutMs: WITNESS_TIMEOUT_MS, outputCapBytes: OUTPUT_CAP_BYTES });

export function validateLimits(limits: SandboxLimits): SandboxLimits {
  const ok = (v: number, max: number) => Number.isInteger(v) && v >= 1 && v <= max;
  if (!ok(limits.timeoutMs, WITNESS_TIMEOUT_MS)) throw new SandboxArgvError(`timeoutMs must be an integer in 1..${WITNESS_TIMEOUT_MS}`);
  if (!ok(limits.outputCapBytes, OUTPUT_CAP_BYTES)) throw new SandboxArgvError(`outputCapBytes must be an integer in 1..${OUTPUT_CAP_BYTES}`);
  return { timeoutMs: limits.timeoutMs, outputCapBytes: limits.outputCapBytes };
}

export function assertPinnedImage(image: string): void {
  if (!PINNED_IMAGE_PATTERN.test(image)) throw new SandboxArgvError("sandbox image must be pinned as name@sha256:<64 hex>");
}

/** `sha256:<hex>` part of a pinned reference. */
export function imageDigestOf(image: string): string {
  assertPinnedImage(image);
  return image.slice(image.indexOf("@") + 1);
}

/**
 * A host staging directory that may be bind-mounted read-only at /in. Must be absolute (POSIX `/x` or Windows
 * `C:\x` / `C:/x`), and is refused if it contains a `..` or `.` segment, a comma, `=`, a quote, a control
 * character, or names the Docker socket/engine pipe (mount-option injection and socket exposure).
 */
export function assertHostMountPath(hostPath: string): void {
  const absolute = /^\//.test(hostPath) || /^[A-Za-z]:[\\/]/.test(hostPath);
  if (!absolute) throw new SandboxArgvError("mount source must be an absolute path");
  // eslint-disable-next-line no-control-regex
  if (/[,="'\u0000-\u001f\u007f]/.test(hostPath)) throw new SandboxArgvError("mount source contains a forbidden character");
  const segments = hostPath.split(/[\\/]/).slice(1);
  if (segments.some((s) => s === ".." || s === ".")) throw new SandboxArgvError("mount source contains a '.' or '..' segment");
  if (/docker\.sock|docker_engine|dockerDesktop/i.test(hostPath)) throw new SandboxArgvError("mount source names the Docker socket");
}

/** In-container entry arguments: absolute paths under /opt/witness, /in or /work, never an option. */
function assertEntry(entry: readonly string[]): void {
  if (entry.length === 0) throw new SandboxArgvError("entry must name a script");
  for (const arg of entry) {
    if (!/^\/(opt\/witness|in|work)(\/[A-Za-z0-9._-]+)*$/.test(arg) || arg.split("/").includes("..")) {
      throw new SandboxArgvError(`entry argument ${JSON.stringify(arg)} is not an allowed in-container path`);
    }
  }
}

export interface DockerRunSpec {
  /** Digest-pinned reference, `name@sha256:<64 hex>`. */
  readonly image: string;
  readonly containerName: string;
  /** Absolute host staging directory, mounted read-only at /in. */
  readonly inputDir: string;
  /** Callsign of the operator who owns the container (agent-ports owner). */
  readonly owner: string;
  /** In-container command after `node`; defaults to the witness entry. Probes pass `["/in/probe.mjs"]`. */
  readonly entry?: readonly string[];
}

/** The complete argv after the `docker` binary. Throws SandboxArgvError on any unsafe input. */
export function buildDockerRunArgv(spec: DockerRunSpec): string[] {
  assertPinnedImage(spec.image);
  if (!CONTAINER_NAME_PATTERN.test(spec.containerName)) throw new SandboxArgvError("invalid container name");
  assertHostMountPath(spec.inputDir);
  if (!/^[A-Za-z0-9][A-Za-z0-9_.-]{0,79}$/.test(spec.owner)) throw new SandboxArgvError("invalid owner label");
  const entry = spec.entry ?? WITNESS_ENTRY;
  assertEntry(entry);
  const p = SANDBOX_POLICY;
  const argv = [
    "run",
    "--rm",
    "--pull", p.pull,
    "--name", spec.containerName,
    "--label", `agentports.project=${AGENT_PORTS_PROJECT}`,
    "--label", `agentports.instance=${AGENT_PORTS_INSTANCE}`,
    "--label", `agentports.owner=${spec.owner}`,
    "--network", p.network,
    "--user", p.user,
    "--read-only",
    "--cap-drop", p.cap_drop,
    "--security-opt", p.security_opt,
    "--tmpfs", p.tmpfs_work,
    "--tmpfs", p.tmpfs_tmp,
    "--memory", p.memory,
    "--memory-swap", p.memory_swap,
    "--cpus", p.cpus,
    "--pids-limit", p.pids_limit,
    "--mount", `type=bind,source=${spec.inputDir},destination=${CONTAINER_INPUT_DIR},readonly`,
    "--workdir", p.workdir,
    "--entrypoint", p.entrypoint,
    spec.image,
    ...entry,
  ];
  assertNoForbiddenArgs(argv);
  return argv;
}

/** Defence in depth: refuse an argv that contains any forbidden flag (exact or `--flag=value` form). */
export function assertNoForbiddenArgs(argv: readonly string[]): void {
  for (const arg of argv) {
    const flag = arg.includes("=") && arg.startsWith("-") ? arg.slice(0, arg.indexOf("=")) : arg;
    if ((FORBIDDEN_ARGS as readonly string[]).includes(flag)) throw new SandboxArgvError(`forbidden docker argument ${flag}`);
  }
}

/** Explicit cleanup after a timeout or output overflow (killing the `docker run` client does not stop the container). */
export function buildCleanupArgv(containerName: string): string[] {
  if (!CONTAINER_NAME_PATTERN.test(containerName)) throw new SandboxArgvError("invalid container name");
  return ["rm", "--force", containerName];
}

/** Presence check after cleanup: empty stdout and exit 0 mean the container no longer exists. */
export function buildPresenceArgv(containerName: string): string[] {
  if (!CONTAINER_NAME_PATTERN.test(containerName)) throw new SandboxArgvError("invalid container name");
  return ["ps", "--all", "--no-trunc", "--filter", `name=^/${containerName}$`, "--format", "{{.Names}}"];
}

/** Host environment variables the Docker CLI process may inherit. No credentials, proxies, NODE_OPTIONS or DOCKER_*. */
export const DOCKER_CLIENT_ENV_ALLOWLIST = ["PATH", "Path", "SystemRoot", "WINDIR", "TEMP", "TMP", "HOME", "USERPROFILE"] as const;
